  SUBROUTINE NLTERM (NL_V,V, BC_PRE)

  USE FFT
  USE MESH
  IMPLICIT REAL*8 (A-H, O-Z)

  COMPLEX*16, DIMENSION(3,0:NXSP,0:NYS,-NZS:NZS) :: NL_V,V
  COMPLEX*16 BC_PRE(0:NXSP,0:1,-NZS:NZS)

  COMPLEX*16, ALLOCATABLE :: W(:,:,:,:)

  ALLOCATE( W(3,0:NXSP,0:NYS,-NZS:NZS) )

! W = rot(V)
  CALL Curl(W,V)

  CALL CROSSTIME(NL_V,V,W)

  BC_PRE = DCMPLX(0.0D0, 0.0D0)
  DO iy=0,NYS
    DO iz=-NZS,NZS
      DO ix=0,NXSP
        W(2,ix,iy,iz)=CWAVXRe(ix)*W(3,ix,iy,iz)-CWAVZRe(iz)*W(1,ix,iy,iz)+NL_V(2,ix,iy,iz)
      ENDDO
    ENDDO
    BC_PRE(0:NXSP,0,-NZS:NZS)=BC_PRE(0:NXSP,0,-NZS:NZS)+W(2,0:NXSP,iy,-NZS:NZS)
    IF(MOD(iy,2)==0) THEN
      BC_PRE(0:NXSP,1,-NZS:NZS)=BC_PRE(0:NXSP,1,-NZS:NZS)-W(2,0:NXSP,iy,-NZS:NZS)
    ELSE
      BC_PRE(0:NXSP,1,-NZS:NZS)=BC_PRE(0:NXSP,1,-NZS:NZS)+W(2,0:NXSP,iy,-NZS:NZS)
    ENDIF
  ENDDO

  DEALLOCATE(W)

  RETURN
  END
! ---&---1---------2---------3---------4---------5---------6---------7--
