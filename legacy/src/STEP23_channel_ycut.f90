  SUBROUTINE STEP23(PRE,BC_PRE,V,RHS_V,BC_V)

  USE MESH
  USE EQSOLVE_PV
  INCLUDE 'com_channel.h'

  COMPLEX*16, DIMENSION(3,0:NXSP,0:NYS,-NZS:NZS) :: V,RHS_V
  COMPLEX*16 BC_V(3,0:NXSP,0:1,-NZS:NZS),PRE(0:NXSP,0:NYS,-NZS:NZS),BC_PRE(0:NXSP,0:1,-NZS:NZS)

  COMPLEX*16, ALLOCATABLE :: RHS_PRE(:,:,:),SIGMA(:,:,:)

  ALLOCATE( RHS_PRE(0:NXSP,0:NYS,-NZS:NZS),SIGMA(0:NXSP,0:1,-NZS:NZS) )

  CALL Div(RHS_PRE,RHS_V)
!   BC_PRE=DCMPLX(0.0D0,0.0D0)

  CALL EQSOLVE_PV_2(PRE,RHS_PRE,BC_PRE, V,RHS_V,BC_V)

  SIGMA(0:NXSP,0,-NZS:NZS)=-WN_V*V(2,0:NXSP,NYS  ,-NZS:NZS) - Re*RHS_V(2,0:NXSP,NYS,-NZS:NZS)
  SIGMA(0:NXSP,1,-NZS:NZS)=-WN_V*V(2,0:NXSP,NYS-1,-NZS:NZS) +&
    & Re*( DFLOAT(2*NYS)*PRE(0:NXSP,NYS,-NZS:NZS) - RHS_V(2,0:NXSP,NYS-1,-NZS:NZS) )

  SIGMA=SIGMA/SIGMA0

  DO iy=0,NYS
    INDEX_iy=MOD(iy+1,2)
    PRE(0:NXSP,iy,-NZS:NZS)=PRE(0:NXSP,iy,-NZS:NZS)+SIGMA(0:NXSP,  INDEX_iy,-NZS:NZS)*PRE0(0:NXSP,iy,-NZS:NZS)
    V(1,0:NXSP,iy,-NZS:NZS)=V(1,0:NXSP,iy,-NZS:NZS)+SIGMA(0:NXSP,  INDEX_iy,-NZS:NZS)*V0(1,0:NXSP,iy,-NZS:NZS)
    V(2,0:NXSP,iy,-NZS:NZS)=V(2,0:NXSP,iy,-NZS:NZS)+SIGMA(0:NXSP,1-INDEX_iy,-NZS:NZS)*V0(2,0:NXSP,iy,-NZS:NZS)
    V(3,0:NXSP,iy,-NZS:NZS)=V(3,0:NXSP,iy,-NZS:NZS)+SIGMA(0:NXSP,  INDEX_iy,-NZS:NZS)*V0(3,0:NXSP,iy,-NZS:NZS)
  ENDDO

  DEALLOCATE(RHS_PRE,SIGMA)

  RETURN
  END
